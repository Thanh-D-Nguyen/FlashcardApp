//
//  When a card is due again, from the learner's saved answers. FSRS-6 with the default parameters, as in py-fsrs 6.3.2
//  (open-spaced-repetition, MIT) configured without learning steps and without fuzzing: every interval is whole days, at
//  least one, and the same input always gives the same schedule. Pure Foundation, no UIKit, no Realm.
//
//  The default parameters were fitted to other people's reviews, not to this app's learners, so nothing here is shown as
//  "probability of remembering" or "learned". Results are checked against the reference library
//  (FlashcardAppTests/FSRSReferenceVectors.swift, generated by scripts/fsrs_reference_vectors.py).
//

import Foundation

/// What a saved answer means for the schedule. The app never sends `easy`: nothing it records says "effortless".
enum ReviewGrade: Int, Equatable {
    case again = 1
    case hard = 2
    case good = 3
    case easy = 4
}

struct FSRSParameters: Equatable {
    /// Stored with every schedule: a schedule made by another algorithm or parameter set is not carried over. Change it together
    /// with the weights, the desired retention or the maximum interval, or old and new schedules would be mixed.
    static let algorithm = "fsrs6-default"
    /// The 21 default FSRS-6 parameters of py-fsrs 6.3.2.
    static let defaultWeights: [Double] = [
        0.212, 1.2931, 2.3065, 8.2956, 6.4133, 0.8334, 3.0194, 0.001, 1.8722, 0.1666, 0.796,
        1.4835, 0.0614, 0.2629, 1.6483, 0.6014, 1.8729, 0.5425, 0.0912, 0.0658, 0.1542
    ]

    var weights = defaultWeights
    var desiredRetention = 0.9
    var maximumInterval = 36_500
}

/// When one card is next due for one kind of answer, and the memory model behind it.
struct ReviewState: Equatable {
    /// `StudyCard.contentVersion` the answers were about; a card whose wording changed starts a new schedule.
    var contentVersion: String
    var algorithm: String
    var stability: Double
    var difficulty: Double
    var due: Date
    var lastReview: Date
    var reviews: Int
    var lapses: Int
}

struct ReviewScheduler {
    static let secondsPerDay: TimeInterval = 86_400

    let parameters: FSRSParameters

    init(parameters: FSRSParameters = FSRSParameters()) {
        precondition(parameters.weights.count == FSRSParameters.defaultWeights.count, "FSRS-6 takes 21 parameters")
        precondition(parameters.desiredRetention > 0 && parameters.desiredRetention < 1, "The desired retention is a chance between 0 and 1")
        precondition(parameters.maximumInterval >= 1, "An interval is at least a day")
        self.parameters = parameters
    }

    /// The grade a saved answer counts as. A right answer that needed help (the reading or the audio was in view) counts as
    /// `hard`, so it grows the interval less than an unaided one; a wrong answer or "needs review" is `again`.
    static func grade(for attempt: ReviewAttempt) -> ReviewGrade {
        switch attempt.result {
        case .incorrect, .needsReview: return .again
        case .correct, .remembered: return attempt.hints.isEmpty ? .good : .hard
        case .typedIncorrect: return .again
        case .typedCorrect: return attempt.hints.isEmpty ? .good : .hard
        }
    }

    /// The schedule after one more answer. `previous` is ignored (the card starts over) when it is for another wording of the
    /// card or was made by another algorithm. An answer dated before the previous one is scheduled as if it happened at the
    /// previous one, so the history never moves backwards and a due date is never earlier than the last review.
    func next(after previous: ReviewState?, grade: ReviewGrade, contentVersion: String, at date: Date) -> ReviewState {
        guard let previous, previous.contentVersion == contentVersion, previous.algorithm == FSRSParameters.algorithm else {
            return state(stability: initialStability(grade), difficulty: initialDifficulty(grade, clamp: true), reviewedAt: date,
                         contentVersion: contentVersion, reviews: 1, lapses: 0)
        }
        let reviewedAt = max(date, previous.lastReview)
        let elapsedDays = (reviewedAt.timeIntervalSince(previous.lastReview) / Self.secondsPerDay).rounded(.down)
        let stability: Double
        if elapsedDays < 1 {
            stability = shortTermStability(previous.stability, grade)
        } else {
            stability = nextStability(difficulty: previous.difficulty, stability: previous.stability,
                                      retrievability: retrievability(stability: previous.stability, elapsedDays: elapsedDays), grade: grade)
        }
        return state(stability: stability, difficulty: nextDifficulty(previous.difficulty, grade), reviewedAt: reviewedAt,
                     contentVersion: contentVersion, reviews: previous.reviews + 1, lapses: previous.lapses + (grade == .again ? 1 : 0))
    }

    func isDue(_ state: ReviewState, at date: Date) -> Bool {
        state.due <= date
    }

    // MARK: FSRS-6 (formulas as in py-fsrs 6.3.2)

    private static let minimumStability = 0.001
    private static let minimumDifficulty = 1.0
    private static let maximumDifficulty = 10.0

    private var weights: [Double] { parameters.weights }
    private var decay: Double { -weights[20] }
    private var factor: Double { pow(0.9, 1 / decay) - 1 }

    private func state(stability: Double, difficulty: Double, reviewedAt: Date, contentVersion: String, reviews: Int, lapses: Int) -> ReviewState {
        let days = intervalDays(stability: stability)
        return ReviewState(contentVersion: contentVersion, algorithm: FSRSParameters.algorithm, stability: stability, difficulty: difficulty,
                           due: reviewedAt.addingTimeInterval(Double(days) * Self.secondsPerDay), lastReview: reviewedAt,
                           reviews: reviews, lapses: lapses)
    }

    /// Whole days until the chance of remembering falls to the desired retention; at least one, at most the cap. Rounds half
    /// to even, like the reference.
    private func intervalDays(stability: Double) -> Int {
        let days = (stability / factor) * (pow(parameters.desiredRetention, 1 / decay) - 1)
        return Int(min(max(days.rounded(.toNearestOrEven), 1), Double(parameters.maximumInterval)))
    }

    private func retrievability(stability: Double, elapsedDays: Double) -> Double {
        pow(1 + factor * max(0, elapsedDays) / stability, decay)
    }

    private func clampStability(_ value: Double) -> Double { max(value, Self.minimumStability) }

    private func clampDifficulty(_ value: Double) -> Double { min(max(value, Self.minimumDifficulty), Self.maximumDifficulty) }

    private func initialStability(_ grade: ReviewGrade) -> Double { clampStability(weights[grade.rawValue - 1]) }

    private func initialDifficulty(_ grade: ReviewGrade, clamp: Bool) -> Double {
        let value = weights[4] - exp(weights[5] * Double(grade.rawValue - 1)) + 1
        return clamp ? clampDifficulty(value) : value
    }

    private func nextDifficulty(_ difficulty: Double, _ grade: ReviewGrade) -> Double {
        let delta = -(weights[6] * Double(grade.rawValue - 3))
        let damped = difficulty + (10 - difficulty) * delta / 9
        let easy = initialDifficulty(.easy, clamp: false)
        return clampDifficulty(weights[7] * easy + (1 - weights[7]) * damped)
    }

    /// For an answer less than a day after the last one.
    private func shortTermStability(_ stability: Double, _ grade: ReviewGrade) -> Double {
        var increase = exp(weights[17] * (Double(grade.rawValue - 3) + weights[18])) * pow(stability, -weights[19])
        if grade != .again { increase = max(increase, 1) }
        return clampStability(stability * increase)
    }

    private func nextStability(difficulty: Double, stability: Double, retrievability: Double, grade: ReviewGrade) -> Double {
        if grade == .again {
            let longTerm = weights[11] * pow(difficulty, -weights[12]) * (pow(stability + 1, weights[13]) - 1) * exp((1 - retrievability) * weights[14])
            let shortTerm = stability / exp(weights[17] * weights[18])
            return clampStability(min(longTerm, shortTerm))
        }
        let hardPenalty = grade == .hard ? weights[15] : 1
        let easyBonus = grade == .easy ? weights[16] : 1
        let growth = exp(weights[8]) * (11 - difficulty) * pow(stability, -weights[9]) * (exp((1 - retrievability) * weights[10]) - 1)
        return clampStability(stability * (1 + growth * hardPenalty * easyBonus))
    }
}
