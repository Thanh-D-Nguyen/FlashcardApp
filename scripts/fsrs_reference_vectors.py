#!/usr/bin/env python3
"""Generates FlashcardAppTests/FSRSReferenceVectors.swift from the reference FSRS implementation.

The app's scheduler (FlashcardApp/Entities/ReviewScheduler.swift) must give the same stability, difficulty and due date as
py-fsrs (open-spaced-repetition, MIT, FSRS-6 with the default 21 parameters) when that library is configured the way the
app uses it: no learning or relearning steps (every interval is whole days, at least one) and no fuzzing. One deliberate
difference is not covered here: a review dated before the previous one is scheduled as if made at the previous one.

    python3 -m venv /tmp/fsrs && /tmp/fsrs/bin/pip install fsrs==6.3.2
    /tmp/fsrs/bin/python scripts/fsrs_reference_vectors.py > FlashcardAppTests/FSRSReferenceVectors.swift
"""
import random
from datetime import datetime, timedelta, timezone

import fsrs
from fsrs import Card, Rating, Scheduler

assert fsrs.__name__ == "fsrs"
T0 = datetime(2026, 1, 1, tzinfo=timezone.utc)
DAY = 86400


def run(name, steps, retention=0.9, maximum_interval=36500):
    """steps: list of (rating, offset_seconds_from_T0) or (rating, None) = exactly when the card is due."""
    scheduler = Scheduler(learning_steps=(), relearning_steps=(), enable_fuzzing=False,
                          desired_retention=retention, maximum_interval=maximum_interval)
    card = Card(card_id=1, due=T0)
    out = []
    for rating, offset in steps:
        when = card.due if offset is None else T0 + timedelta(seconds=offset)
        card, _ = scheduler.review_card(card, Rating(rating), when)
        out.append((rating, (when - T0).total_seconds(), card.stability, card.difficulty, (card.due - T0).total_seconds(), int(card.state)))
    return name, retention, maximum_interval, out


scenarios = [
    run("good streak", [(3, 0)] + [(3, None)] * 7),
    run("again first then recovery", [(1, 0), (3, None), (3, None), (2, None)]),
    run("hard first", [(2, 0), (3, None), (3, None)]),
    run("easy first", [(4, 0), (4, None), (3, None)]),
    run("lapse after a good run", [(3, 0), (3, None), (3, None), (1, None), (3, None), (3, None)]),
    run("early reviews", [(3, 0), (3, 1 * DAY), (3, 3 * DAY), (3, 10 * DAY), (3, 25 * DAY)]),
    run("late reviews", [(3, 0), (3, 1 * DAY + 30 * DAY), (1, 90 * DAY), (3, 91 * DAY + 400)]),
    run("same day reviews", [(3, 0), (3, 2 * 3600), (1, 3 * 3600), (2, 5 * 3600), (3, 6 * 3600), (3, 2 * DAY)]),
    run("good streak with 80 percent retention", [(3, 0)] + [(3, None)] * 5, retention=0.8),
    run("good streak with a 30 day cap", [(3, 0)] + [(3, None)] * 6, maximum_interval=30),
]

rng = random.Random(42)
clock, mixed = 0, []
for _ in range(30):
    clock += int(rng.choice([0.2, 1, 2, 5, 9, 20, 40]) * DAY * rng.random())
    mixed.append((rng.choice([1, 2, 3, 3, 3, 4]), clock))
scenarios.append(run("random history (seed 42)", mixed))


def literal(value):
    return repr(float(value))


print("// Generated by scripts/fsrs_reference_vectors.py from py-fsrs %s (FSRS-6, default parameters, no steps, no fuzz). Do not edit." % getattr(fsrs, "__version__", "6.3.2"))
print("// `at` and `due` are seconds after 2026-01-01T00:00:00Z. `state` is the reference state (2 = review).")
print("struct FSRSVectorStep { let grade: Int; let at: Double; let stability: Double; let difficulty: Double; let due: Double; let state: Int }")
print("struct FSRSVector { let name: String; let desiredRetention: Double; let maximumInterval: Int; let steps: [FSRSVectorStep] }")
print("")
print("let fsrsReferenceVectors: [FSRSVector] = [")
for name, retention, cap, steps in scenarios:
    print('    FSRSVector(name: "%s", desiredRetention: %s, maximumInterval: %d, steps: [' % (name, literal(retention), cap))
    for grade, at, stability, difficulty, due, state in steps:
        print("        FSRSVectorStep(grade: %d, at: %s, stability: %s, difficulty: %s, due: %s, state: %d)," % (grade, literal(at), literal(stability), literal(difficulty), literal(due), state))
    print("    ]),")
print("]")
